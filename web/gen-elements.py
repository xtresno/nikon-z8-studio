"""Generate src/elements.d.ts: every element id in index.html with its DOM
type, so `$("#burst")` is an HTMLInputElement to the compiler. Run after
editing index.html: python3 gen-elements.py"""
import re
from html.parser import HTMLParser
TYPES = {"input": "HTMLInputElement", "select": "HTMLSelectElement", "button": "HTMLButtonElement",
         "img": "HTMLImageElement", "video": "HTMLVideoElement", "audio": "HTMLAudioElement",
         "canvas": "HTMLCanvasElement", "dialog": "HTMLDialogElement", "form": "HTMLFormElement",
         "textarea": "HTMLTextAreaElement", "output": "HTMLOutputElement", "a": "HTMLAnchorElement",
         "label": "HTMLLabelElement", "table": "HTMLTableElement", "details": "HTMLDetailsElement"}
ids = {}
class P(HTMLParser):
    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if "id" in a:
            ids[a["id"]] = TYPES.get(tag, "HTMLElement")
P().feed(open("index.html", encoding="utf-8").read())
# Created by the script at run time, not present in index.html.
DYNAMIC = {"goPrev": "HTMLButtonElement"}
ids.update(DYNAMIC)
lines = ["// GENERATED by gen-elements.py from index.html. Do not edit by hand.",
         "interface Z8Elements {"]
lines += [f'  "#{k}": {v};' for k, v in sorted(ids.items())]
lines += ["}", ""]
open("src/elements.d.ts", "w").write("\n".join(lines))
print(len(ids), "ids")
